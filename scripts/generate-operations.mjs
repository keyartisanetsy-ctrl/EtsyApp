/**
 * Generates a complete, typed-ish operation table for every Etsy Open API v3
 * endpoint directly from the official OpenAPI 3.0.2 document.
 *
 * Running this is what guarantees the client covers the *entire* reference
 * (all tags, all operations) instead of a hand-picked subset. Re-run it
 * whenever Etsy publishes a spec update:  npm run codegen
 */
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const SPEC = path.join(root, 'docs', 'etsy-oas.json');
const OUT = path.join(root, 'server', 'src', 'etsy', 'operations.generated.js');
const METHODS = ['get', 'post', 'put', 'patch', 'delete'];

const bodyKind = (ct) =>
  ct.includes('json') ? 'json'
  : ct.includes('x-www-form-urlencoded') ? 'form'
  : ct.includes('multipart') ? 'multipart'
  : 'json';

function paramInfo(p) {
  const s = p.schema || {};
  const out = { name: p.name, in: p.in, required: !!p.required, type: s.type || 'string' };
  if (s.enum) out.enum = s.enum;
  if (s.default !== undefined) out.default = s.default;
  if (s.items?.type) out.itemType = s.items.type;
  return out;
}

const spec = JSON.parse(await readFile(SPEC, 'utf8'));
const ops = [];

for (const [urlPath, item] of Object.entries(spec.paths)) {
  const shared = (item.parameters || []).map(paramInfo);
  for (const method of METHODS) {
    const op = item[method];
    if (!op) continue;

    const params = [...shared, ...(op.parameters || []).map(paramInfo)];
    const scopes = [];
    for (const sec of op.security || []) for (const v of Object.values(sec)) scopes.push(...v);

    let body = null;
    const rb = op.requestBody;
    if (rb?.content) {
      const [ct, media] = Object.entries(rb.content)[0];
      const schema = media.schema || {};
      body = {
        kind: bodyKind(ct),
        contentType: ct,
        required: schema.required || [],
        props: Object.fromEntries(
          Object.entries(schema.properties || {}).map(([k, v]) => {
            const e = { type: v.type };
            if (v.enum) e.enum = v.enum;
            if (v.format === 'binary') e.binary = true;
            if (v.items?.type) e.itemType = v.items.type;
            return [k, e];
          }),
        ),
      };
    }

    ops.push({
      operationId: op.operationId,
      method: method.toUpperCase(),
      path: urlPath,
      tag: (op.tags || ['Other'])[0],
      summary: (op.summary || '').trim(),
      // Etsy marks endpoints that are still gated behind an application review.
      restricted: /restricted|feature is not available|limited release/i.test(op.description || ''),
      scopes: [...new Set(scopes)],
      pathParams: params.filter((p) => p.in === 'path').map((p) => p.name),
      query: params.filter((p) => p.in === 'query'),
      headers: params.filter((p) => p.in === 'header').map((p) => p.name),
      body,
    });
  }
}

ops.sort((a, b) => a.operationId.localeCompare(b.operationId));
const byTag = {};
for (const o of ops) (byTag[o.tag] ||= []).push(o.operationId);

const banner = `// AUTO-GENERATED by scripts/generate-operations.mjs -- DO NOT EDIT BY HAND.
// Source: Etsy Open API v3 (${spec.info.version}) OpenAPI ${spec.openapi}
// ${ops.length} operations across ${Object.keys(byTag).length} tags. Regenerate with: npm run codegen
`;

const file = `${banner}
/** Every operation in the Etsy Open API v3 reference, keyed by operationId. */
export const OPERATIONS = ${JSON.stringify(Object.fromEntries(ops.map((o) => [o.operationId, o])), null, 2)};

/** operationIds grouped by their reference-documentation tag. */
export const OPERATIONS_BY_TAG = ${JSON.stringify(byTag, null, 2)};

export const OPERATION_IDS = Object.keys(OPERATIONS);
export const OPERATION_COUNT = ${ops.length};

/** OAuth scopes required by at least one operation. */
export const ALL_SCOPES = ${JSON.stringify([...new Set(ops.flatMap((o) => o.scopes))].sort())};
`;

await writeFile(OUT, file);
console.log(`generated ${ops.length} operations -> ${path.relative(root, OUT)}`);
for (const [t, list] of Object.entries(byTag)) console.log(`  ${t.padEnd(28)} ${list.length}`);
